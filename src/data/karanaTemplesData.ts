export function getKaranaTempleRemedy(karanaEn: string, karanaTa: string): TempleRemedy {
  const normEn = karanaEn.toLowerCase();
  const normTa = karanaTa;

  if (normEn.includes('bava') || normTa.includes('பவ')) return KARANA_TEMPLES_DB[1];
  if (normEn.includes('balava') || normTa.includes('பாலவ')) return KARANA_TEMPLES_DB[2];
  if (normEn.includes('kaulava') || normTa.includes('கௌலவ')) return KARANA_TEMPLES_DB[3];
  if (normEn.includes('taitila') || normTa.includes('தைதுலை')) return KARANA_TEMPLES_DB[4];
  if (normEn.includes('garaja') || normTa.includes('கரசை')) return KARANA_TEMPLES_DB[5];
  if (normEn.includes('vanija') || normTa.includes('வணிஜை')) return KARANA_TEMPLES_DB[6];
  if (normEn.includes('vishti') || normEn.includes('bhadra') || normTa.includes('பத்ரை') || normTa.includes('விஷ்டி')) return KARANA_TEMPLES_DB[7];
  if (normEn.includes('shakuni') || normTa.includes('சகுனி')) return KARANA_TEMPLES_DB[8];
  if (normEn.includes('chatushpada') || normTa.includes('சதுஷ்பாத')) return KARANA_TEMPLES_DB[9];
  if (normEn.includes('naga') || normTa.includes('நாகவ')) return KARANA_TEMPLES_DB[10];
  if (normEn.includes('kintughna') || normTa.includes('கிமஸ்துக்ன')) return KARANA_TEMPLES_DB[11];

  return KARANA_TEMPLES_DB[1];
}
